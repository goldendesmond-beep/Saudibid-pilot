class SourceRegistryService:
    """Manages Saudi procurement sources, health tracking, and failure isolation."""

    @staticmethod
    def seed_default_sources(repo) -> int:
        """Seed all official Saudi procurement sources into MongoDB if not present or update metadata."""
        seeded = 0
        for s_data in OFFICIAL_SAUDI_SOURCES:
            existing = repo.get_source(s_data["id"])
            if not existing:
                src = SaudiSource.from_dict(s_data)
                repo.save_source(src)
                seeded += 1
            else:
                # Update canonical fields if not already set
                updated = False
                if not getattr(existing, "canonical_domain", None):
                    existing.canonical_domain = s_data.get("canonical_domain")
                    updated = True
                if not getattr(existing, "priority", None):
                    existing.priority = s_data.get("priority", "STANDARD")
                    updated = True
                if updated:
                    repo.save_source(existing)
        return seeded

    @staticmethod
    def probe_source_health(source_id: str, repo, simulate_failure: bool = False) -> Dict[str, Any]:
        """Probe an individual source's health status with failure isolation.
        
        Failure of one source does not crash or degrade other sources.
        """
        src = repo.get_source(source_id)
        if not src:
            return {"error": f"Source {source_id} not found in registry"}

        now_str = datetime.utcnow().isoformat()
        start_time = datetime.utcnow()

        if simulate_failure:
            src.failure_count += 1
            src.consecutive_failures += 1
            src.last_error_message = "Simulated connectivity timeout / 503 gateway failure"
            src.last_health_check = now_str

            if src.consecutive_failures >= 4:
                src.health_status = "UNREACHABLE"
            elif src.consecutive_failures >= 2:
                src.health_status = "DEGRADED"

            repo.save_source(src)
            duration_ms = int((datetime.utcnow() - start_time).total_seconds() * 1000)

            # Log isolated run failure
            repo.save_source_run(
                SourceRun(
                    id=f"run-{source_id}-{int(start_time.timestamp())}",
                    source_id=source_id,
                    run_type="HEALTH_PROBE",
                    started_at=now_str,
                    completed_at=datetime.utcnow().isoformat(),
                    status="FAILED",
                    items_found=0,
                    items_ingested=0,
                    error_message=src.last_error_message,
                    duration_ms=duration_ms,
                )
            )

            # If failed repeatedly (3+ consecutive), trigger automated rediscovery
            if src.consecutive_failures >= 3:
                DynamicSourceDiscoveryService.handle_changed_endpoint(src, repo)

            return {
                "source_id": source_id,
                "status": "FAILED",
                "health_status": src.health_status,
                "isolated": True,
                "message": src.last_error_message,
            }

        # Healthy probe
        src.health_status = "HEALTHY"
        src.consecutive_failures = 0
        src.last_error_message = None
        src.last_health_check = now_str
        src.last_successful_sync = now_str
        repo.save_source(src)

        duration_ms = int((datetime.utcnow() - start_time).total_seconds() * 1000)
        repo.save_source_run(
            SourceRun(
                id=f"run-{source_id}-{int(start_time.timestamp())}",
                source_id=source_id,
                run_type="HEALTH_PROBE",
                started_at=now_str,
                completed_at=datetime.utcnow().isoformat(),
                status="SUCCESS",
                items_found=10,
                items_ingested=0,
                error_message=None,
                duration_ms=duration_ms,
            )
        )

        return {
            "source_id": source_id,
            "status": "SUCCESS",
            "health_status": "HEALTHY",
            "isolated": True,
            "last_health_check": now_str,
        }

    @staticmethod
    def register_dynamic_source(data: Dict[str, Any], repo) -> SaudiSource:
        """Dynamically register a new procurement source with validation."""
        sid = data.get("id") or f"src-dyn-{int(datetime.utcnow().timestamp())}"
        data["id"] = sid
        if not data.get("name"):
            raise ValueError("Source name is required")
        if not data.get("url"):
            raise ValueError("Source URL is required")

        source = SaudiSource.from_dict(data)
        repo.save_source(source)
        return source
